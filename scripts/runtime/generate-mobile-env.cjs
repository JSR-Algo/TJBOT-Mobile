const fs = require('fs');
const path = require('path');

const ENV_KEYS = [
  'TBOT_API_URL',
  'TBOT_AI_URL',
  'EXPO_PUBLIC_API_BASE_URL',
  'EXPO_PUBLIC_GEMINI_LIVE_MODEL',
  'EXPO_PUBLIC_VOICE_BARGE_IN_BUDGET_MS',
  'EXPO_PUBLIC_VOICE_TEST_HARNESS',
  'EXPO_PUBLIC_VOICE_CANCEL_UNACK_RECOVERY',
  'EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS',
  'EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS_UNTIL',
];

function loadDotEnv(envPath) {
  const env = {};
  if (!fs.existsSync(envPath)) return env;

  for (const line of fs.readFileSync(envPath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const separator = trimmed.indexOf('=');
    if (separator < 0) continue;
    const key = trimmed.slice(0, separator).trim();
    const value = trimmed.slice(separator + 1).trim().replace(/^["']|["']$/g, '');
    env[key] = value;
  }
  return env;
}

function sanitizedAiUrl(value) {
  const trimmed = (value || '').replace(/\/+$/, '');
  if (trimmed === 'http://localhost:3001/api/ai' || trimmed === 'http://127.0.0.1:3001/api/ai') {
    return '';
  }
  return value || '';
}

function createRuntimeEnv(repoRoot, processEnv = process.env) {
  const env = loadDotEnv(path.join(repoRoot, '.env'));
  for (const key of ENV_KEYS) {
    if (processEnv[key] !== undefined) env[key] = processEnv[key];
  }

  return {
    TBOT_API_URL: env.TBOT_API_URL || env.EXPO_PUBLIC_API_BASE_URL || '',
    TBOT_AI_URL: sanitizedAiUrl(env.TBOT_AI_URL),
    EXPO_PUBLIC_GEMINI_LIVE_MODEL: env.EXPO_PUBLIC_GEMINI_LIVE_MODEL || '',
    EXPO_PUBLIC_VOICE_BARGE_IN_BUDGET_MS: env.EXPO_PUBLIC_VOICE_BARGE_IN_BUDGET_MS || '',
    EXPO_PUBLIC_VOICE_TEST_HARNESS: env.EXPO_PUBLIC_VOICE_TEST_HARNESS || '',
    EXPO_PUBLIC_VOICE_CANCEL_UNACK_RECOVERY: env.EXPO_PUBLIC_VOICE_CANCEL_UNACK_RECOVERY || '',
    EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS: env.EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS || '',
    EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS_UNTIL: env.EXPO_PUBLIC_PARENT_PROGRESS_DIAGNOSTICS_UNTIL || '',
  };
}

function writeRuntimeEnv(repoRoot, processEnv = process.env, outputPath = path.join(repoRoot, '.runtime', '__env__.ts')) {
  const env = createRuntimeEnv(repoRoot, processEnv);
  const entries = Object.entries(env).map(([key, value]) => `  ${key}: ${JSON.stringify(value)},`).join('\n');
  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(outputPath, `// AUTO-GENERATED by Metro - do not edit manually\nexport const ENV = {\n${entries}\n};\n`);
  return outputPath;
}

module.exports = { createRuntimeEnv, writeRuntimeEnv };

if (require.main === module) {
  writeRuntimeEnv(path.resolve(__dirname, '../..'));
}
