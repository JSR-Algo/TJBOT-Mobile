#!/usr/bin/env node
// build-global-erd.mjs — concatenate every domain .dbml + _shared/*.dbml into a single global ERD file.
//
// Output: docs/erd/_global/global-erd.dbml.
// Sections separated by `// === <NN>-<system> ===` headers, sorted by folder name (lexicographic — folders are zero-padded).
// Skips templates/ and _global/.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(here, '..', '..');
const ERD_DIR = path.join(PROJECT_ROOT, 'docs', 'erd');
const OUT = path.join(ERD_DIR, '_global', 'global-erd.dbml');

function listDomains() {
  if (!fs.existsSync(ERD_DIR)) return [];
  return fs.readdirSync(ERD_DIR, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name)
    .filter(n => n !== 'templates' && n !== '_global')
    .sort();
}

function dbmlsIn(domainDir) {
  if (!fs.existsSync(domainDir)) return [];
  return fs.readdirSync(domainDir, { withFileTypes: true })
    .filter(d => d.isFile() && d.name.endsWith('.dbml'))
    .map(d => path.join(domainDir, d.name))
    .sort();
}

const domains = listDomains();
const chunks = [];
chunks.push('// global-erd.dbml — GENERATED by scripts/erd/build-global-erd.mjs. Do not edit by hand.');
chunks.push(`// Generated: ${new Date().toISOString()}`);
chunks.push('// Source: docs/erd/<NN>-<system>/*.dbml + docs/erd/_shared/*.dbml');
chunks.push('');

let totalFiles = 0;
for (const dom of domains) {
  const files = dbmlsIn(path.join(ERD_DIR, dom));
  if (!files.length) continue;
  chunks.push(`// === ${dom} ===`);
  for (const f of files) {
    chunks.push(`// --- ${path.relative(PROJECT_ROOT, f)} ---`);
    chunks.push(fs.readFileSync(f, 'utf8').replace(/\s+$/g, ''));
    chunks.push('');
    totalFiles++;
  }
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, chunks.join('\n') + '\n');
console.log(`[build-global-erd] wrote ${path.relative(PROJECT_ROOT, OUT)} (${totalFiles} entity files across ${domains.length} domains)`);
