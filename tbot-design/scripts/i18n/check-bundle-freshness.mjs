#!/usr/bin/env node
// check-bundle-freshness.mjs
// Asserts locales/bundle.js matches the output the generator would produce
// from current locales/{en,vi}.json. Exit 1 on stale bundle (someone edited
// the JSON sources without running `npm run i18n:bundle`).
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const en = JSON.parse(readFileSync(join(root, 'locales', 'en.json'), 'utf8'));
const vi = JSON.parse(readFileSync(join(root, 'locales', 'vi.json'), 'utf8'));
const expected = `// GENERATED by scripts/i18n/build-locales-bundle.mjs — do not edit by hand.
// Source of truth: locales/en.json + locales/vi.json. Run \`npm run i18n:bundle\`.
window.__tbotLocales = ${JSON.stringify({ en, vi }, null, 2)};
`;
const actual = readFileSync(join(root, 'locales', 'bundle.js'), 'utf8');
if (actual === expected) {
  console.log('locales/bundle.js is in sync with locales/{en,vi}.json');
  process.exit(0);
}
console.error('locales/bundle.js is STALE. Run `npm run i18n:bundle` and commit.');
process.exit(1);
