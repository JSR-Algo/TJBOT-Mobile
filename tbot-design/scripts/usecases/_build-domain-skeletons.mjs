#!/usr/bin/env node
// Writes 14 docs/usecases/domains/<d>/use-cases.md skeleton files,
// one H2 anchor per UC owned by that domain (empty body — Lane A/B/C/D fills).
// Idempotent.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..', '..');
const INDEX = JSON.parse(readFileSync(resolve(ROOT, 'docs/usecases/reference/use-case-index.json'), 'utf8'));

const byDomain = {};
for (const e of INDEX.entries) {
  (byDomain[e.domain] ??= []).push(e);
}

const LANES = {
  auth: 'A', onboarding: 'A',
  'kid-hub': 'B', 'lesson-session': 'B', 'course-browse': 'B',
  progress: 'C', 'parent-gate': 'C', 'parent-summary': 'C', purchase: 'C',
  'device-pairing': 'D', 'device-mgmt': 'D', 'robot-mgmt': 'D',
  'course-library': 'D', 'fallback-shell': 'D',
};

for (const [domain, entries] of Object.entries(byDomain)) {
  entries.sort((a, b) => a.id.localeCompare(b.id, 'en', { numeric: true }));
  const lane = LANES[domain] ?? 'Z';
  const path = resolve(ROOT, `docs/usecases/domains/${domain}/use-cases.md`);
  mkdirSync(dirname(path), { recursive: true });
  const lines = [
    `# Use Cases — \`${domain}\``,
    '',
    `> **Owning lane:** Lane ${lane}. **UC count:** ${entries.length}. Skeleton generated by Lane Z (Phase 0). Bodies filled by Lane ${lane} (Phase 1).`,
    '>',
    `> Each H2 below corresponds to one UC ID from \`reference/use-case-index.json\`. Cross-domain edges: see \`reference/cross-domain-edges.json\`. Backend mapping: see \`backend-mapping.md\`. Edge cases: see \`edge-cases.md\`.`,
    '',
    '---',
    '',
  ];
  for (const e of entries) {
    lines.push(`## ${e.id} — ${e.name}`);
    lines.push('');
    lines.push('- **Goal:** _TBD by Lane ' + lane + '_');
    lines.push('- **Trigger:** _TBD_');
    lines.push('- **Preconditions:** _TBD_');
    lines.push('- **Main Flow:**');
    lines.push('  1. _TBD_');
    lines.push('- **Postconditions:** _TBD_');
    lines.push('');
  }
  writeFileSync(path, lines.join('\n'));
  console.log(`Wrote ${path} (${entries.length} UCs)`);
}
